"""HTTP routes for the DocuGen service."""
from __future__ import annotations

from fastapi import APIRouter, HTTPException

from . import service
from .schemas import (
    CustomsFilingRequest,
    CustomsFilingResponse,
    DealDocumentsListResponse,
    DocumentResponse,
    GenerateDocumentRequest,
)
from .service import (
    DealNotFoundError,
    DocuGenError,
    DocumentNotFoundError,
)

router = APIRouter(prefix="/docugen", tags=["docugen"])


@router.get("/health")
async def health() -> dict[str, str]:
    return {"status": "ok", "service": "docugen"}


# ---------------------------------------------------------------------------
# Document generation
# ---------------------------------------------------------------------------

@router.post("/documents", response_model=DocumentResponse, status_code=201)
async def generate_document(payload: GenerateDocumentRequest) -> DocumentResponse:
    """Generate a trade or customs document for a deal.

    Supported types: CI, PL, CoO, SDF, SHIPPING_BILL.
    PI is generated by the DealMaker service — use POST /dealmaker/pi instead.
    """
    try:
        return await service.generate_document(payload)
    except DealNotFoundError as exc:
        raise HTTPException(status_code=404, detail=str(exc)) from exc
    except DocuGenError as exc:
        raise HTTPException(status_code=422, detail=str(exc)) from exc


@router.get("/documents/{doc_id}", response_model=DocumentResponse)
async def get_document(doc_id: str) -> DocumentResponse:
    """Fetch a generated document by ID."""
    try:
        return await service.get_document(doc_id)
    except DocumentNotFoundError as exc:
        raise HTTPException(status_code=404, detail=str(exc)) from exc


@router.get("/deals/{deal_id}/documents", response_model=DealDocumentsListResponse)
async def list_deal_documents(deal_id: str) -> DealDocumentsListResponse:
    """List all DocuGen documents for a deal."""
    return await service.list_deal_documents(deal_id)


# ---------------------------------------------------------------------------
# Customs filing
# ---------------------------------------------------------------------------

@router.post("/customs/file", response_model=CustomsFilingResponse, status_code=201)
async def file_customs(payload: CustomsFilingRequest) -> CustomsFilingResponse:
    """Trigger Shipping Bill filing via ICEGATE for a deal.

    Generates a Shipping Bill document if one has not already been created.
    Returns the Shipping Bill number and Let Export Order (LEO) on success.
    """
    try:
        return await service.file_customs(payload)
    except DealNotFoundError as exc:
        raise HTTPException(status_code=404, detail=str(exc)) from exc
    except DocuGenError as exc:
        raise HTTPException(status_code=422, detail=str(exc)) from exc
